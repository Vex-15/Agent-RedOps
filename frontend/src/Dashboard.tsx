// ── Small UI atoms ─────────────────────────────────────────────────────

function MetricCard({ label, value, note, tone = 'ink' }: { label: string; value: string | number; note: string; tone?: 'ink' | 'red' | 'green' | 'amber' }) {
  const toneClass = { ink: 'text-ink', red: 'text-crimson', green: 'text-emerald-600', amber: 'text-amber-600' }[tone];
  return (
    <div className="panel panel-shadow p-5">
      <div className="text-[11px] font-semibold uppercase tracking-wider text-muted">{label}</div>
      <div className={`text-2xl font-bold mt-1 tabular-nums ${toneClass}`}>{value}</div>
      <div className="text-xs text-muted mt-2">{note}</div>
    </div>
  );
}

// ── Report export ──────────────────────────────────────────────────────

function download(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function buildMarkdownReport(detail: RunDetail): string {
  const lines: string[] = [];
  lines.push(`# RedOps Security Report — ${detail.scenario_name}`);
  lines.push('');
  lines.push(`- **Run ID:** \`${detail.run_id}\``);
  lines.push(`- **Status:** ${detail.status}`);
  if (detail.error) lines.push(`- **Error:** \`${detail.error}\``);
  lines.push(`- **Latency:** ${detail.latency_ms} ms`);
  lines.push(`- **Trace events:** ${detail.trace.length}`);
  lines.push(`- **Attack paths:** ${detail.attack_paths.length}`);
  lines.push(`- **Generated:** ${new Date().toISOString()}`);
  lines.push('');

  lines.push('## Findings');
  if (detail.violations.length === 0) {
    lines.push('_No policy violations detected._');
  }
  for (const v of detail.violations) {
    lines.push('');
    lines.push(`### [${v.severity}] ${v.title}`);
    lines.push(`- **Category:** \`${v.category}\``);
    lines.push(`- **Description:** ${v.description}`);
    if (v.root_cause) lines.push(`- **Root cause:** ${v.root_cause}`);
    if (v.evidence_event_ids.length) {
      lines.push(`- **Evidence events:** ${v.evidence_event_ids.map((id) => `\`${id}\``).join(', ')}`);
    }
  }

  lines.push('');
  lines.push('## Attack Paths');
  if (detail.attack_paths.length === 0) lines.push('_None._');
  for (const ap of detail.attack_paths) {
    lines.push('');
    lines.push(`- **Entry:** ${ap.entry_point} (${ap.length} events)`);
    lines.push(`  - Impact: ${ap.impact}`);
  }

  lines.push('');
  lines.push('## Verified Defenses');
  if (detail.defenses.length === 0) lines.push('_No defenses required._');
  for (const d of detail.defenses) {
    lines.push('');
    lines.push(`### ${d.defense.name} — ${d.verdict}`);
    lines.push(`- **What it does:** ${d.defense.description}`);
    lines.push(`- **Result:** ${d.explanation}`);
    lines.push(`- **Code location:** \`${d.defense.code_location}\``);
    lines.push('- **Recommended fix:**');
    lines.push('');
    lines.push('```');
    lines.push(d.defense.fix_description);
    lines.push('```');
  }

  lines.push('');
  lines.push('---');
  lines.push('_Generated by RedOps · simulated environment · no real purchases executed_');
  return lines.join('\n');
}


/**
 * Renders a run as it executes: a phase ticker over a trace that grows
 * event by event.  Defended re-run events are tagged so the audience can
 * see the guards intercept the attack on the second pass.
 */
function LiveExecutionPanel({ state, onCancel }: { state: LiveState; onCancel: () => void }) {
  const done = state.phase === 'done';
  const blocked = state.defenses.filter((d) => d.verdict === 'blocked').length;

  return (
    <section className="panel panel-shadow p-5 lg:sticky lg:top-20 lg:max-h-[calc(100vh-6rem)] lg:overflow-y-auto border-crimson/30">
      <div className="flex items-center justify-between mb-3 gap-2">
        <div className="flex items-center gap-2">
          <span className="relative flex h-2.5 w-2.5">
            {!done && (
              <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-crimson opacity-70" />
            )}
            <span
              className={`relative inline-flex rounded-full h-2.5 w-2.5 ${
                done ? 'bg-emerald-500' : state.errored ? 'bg-amber-500' : 'bg-crimson'
              }`}
            />
          </span>
          <h2 className="text-sm font-semibold uppercase tracking-wider">
            {done ? 'Run Complete' : 'Live Execution'}
          </h2>
          {state.total != null && state.total > 0 && (
            <span className="font-mono text-[11px] text-muted">
              {(state.index ?? 0) + 1}/{state.total}
            </span>
          )}
        </div>
        <button
          onClick={onCancel}
          className="text-[11px] font-mono border border-line px-2 py-1 rounded hover:bg-lab transition-colors"
        >
          {done ? 'Close' : 'Stop'}
        </button>
      </div>

      <div className="bg-lab border border-line rounded-lg p-3.5 text-xs mb-3">
        <div className="font-medium text-sm">{state.scenarioName || '…'}</div>
        <div className="mt-1.5 flex flex-wrap items-center gap-2 text-muted">
          <Badge tone={done ? 'green' : state.errored ? 'amber' : 'red'}>
            {PHASE_LABEL[state.phase] ?? state.phase}
          </Badge>
          <span>{state.message}</span>
        </div>
        <div className="mt-2.5 flex gap-4">
          <span>
            Events <b className="tabular-nums">{state.events.length}</b>
          </span>
          <span>
            Findings <b className="text-crimson tabular-nums">{state.findings.length}</b>
          </span>
          <span>
            Guards blocked <b className="text-emerald-700 tabular-nums">{blocked}</b>
          </span>
        </div>
      </div>

      <div className="border border-line rounded-lg overflow-hidden bg-lab/40">
        <div className="px-3 py-1.5 bg-panel border-b border-line flex items-center justify-between">
          <span className="text-[10px] font-semibold uppercase tracking-wider">Execution trace</span>
          <span className="font-mono text-[9px] text-muted">
            {done ? 'final' : 'receiving events…'}
          </span>
        </div>
        <div className="divide-y divide-line max-h-[330px] overflow-y-auto">
          {state.events.length === 0 && (
            <div className="px-3 py-5 text-center text-xs text-muted">Waiting for the first event…</div>
          )}
          {state.events.map(({ event: ev, phase: evPhase }, i) => {
            const isError = ev.kind === 'error';
            const isGuard = Boolean(ev.metadata?.defense_triggered);
            const untrusted = !ev.trusted && !isGuard;
            return (
              <div
                key={`${ev.id}-${i}`}
                className={`flex gap-2.5 px-3 py-1.5 ${isError || untrusted ? 'bg-crimson-faint/50' : ''}`}
              >
                <span
                  className={`mt-1.5 w-[7px] h-[7px] shrink-0 rounded-full ${
                    isError || untrusted ? 'bg-crimson' : isGuard ? 'bg-emerald-500' : 'bg-emerald-500/60'
                  }`}
                />
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-1.5">
                    <span
                      className={`text-[11px] font-medium ${
                        isError || untrusted ? 'text-crimson' : isGuard ? 'text-emerald-700' : 'text-ink'
                      }`}
                    >
                      {ev.action}
                    </span>
                    {evPhase === 'defend' && <Badge tone="green">defended</Badge>}
                    {untrusted && <Badge tone="red">untrusted</Badge>}
                    {isError && <Badge tone="red">error</Badge>}
                    {isGuard && <Badge tone="green">guard</Badge>}
                  </div>
                  <div className="text-[9px] text-muted font-mono">
                    {ev.agent} · {ev.kind}
                  </div>
                </div>
                <span className="font-mono text-[9px] text-muted pt-0.5 shrink-0">
                  {ev.timestamp.slice(11, 19)}
                </span>
              </div>
            );
          })}
        </div>
      </div>

      {state.findings.length > 0 && (
        <div className="mt-3 border border-crimson/20 bg-crimson-faint/40 rounded-lg p-3">
          <div className="text-[10px] font-semibold text-crimson uppercase tracking-wider mb-1.5">
            Findings so far ({state.findings.length})
          </div>
          <ul className="space-y-1">
            {state.findings.map((v) => (
              <li key={v.id} className="text-[12px] flex items-center gap-2">
                <Badge tone={v.severity === 'critical' || v.severity === 'high' ? 'red' : 'amber'}>
                  {v.severity}
                </Badge>
                <span className="text-ink">{v.title}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {done && state.runIds.length > 0 && (
        <p className="text-[11px] text-muted mt-3">
          Run persisted · full trace, root cause and code-level fixes are in the inspector below.
        </p>
      )}
      {state.errored && (
        <p className="text-[11px] text-amber-700 mt-3">The stream reported an error — showing what was received.</p>
      )}
    </section>
  );
}

// ── Console ────────────────────────────────────────────────────────────

export default function Dashboard() {
  const [scenarios, setScenarios] = useState<ScenarioItem[]>([]);
  const [runs, setRuns] = useState<RunItem[]>([]);
  const [metrics, setMetrics] = useState<DashboardMetrics | null>(null);
  const [selectedRunId, setSelectedRunId] = useState<string | null>(null);
  const [detail, setDetail] = useState<RunDetail | null>(null);
  const [busyId, setBusyId] = useState<number | null>(null);
  const [allBusy, setAllBusy] = useState(false);
  const [live, setLive] = useState<boolean | null>(null);
  const [loading, setLoading] = useState(true);
  const [openEventId, setOpenEventId] = useState<string | null>(null);
  const [selectedViolationId, setSelectedViolationId] = useState<string | null>(null);
  const [liveRun, setLiveRun] = useState<LiveState | null>(null);

  const refresh = useCallback(async () => {
    setLoading(true);
    const [sc, rn, mt] = await Promise.all([getScenarios(), getRuns(), getDashboardMetrics()]);
    setScenarios(sc.data);
    setRuns(rn.data);
    setMetrics(mt.data);
    setLive(sc.live && rn.live && mt.live);
    setLoading(false);
  }, []);

  useEffect(() => {
    void refresh();
  }, [refresh]);

  const loadDetail = async (runId: string | null) => {
    setSelectedRunId(runId);
    setDetail(null);
    if (!runId) return;
    const res = await getRunDetail(runId);
    setDetail(res.data);
    setSelectedViolationId(res.data.violations[0]?.id ?? null);
  };

  /**
   * Run one scenario.  Against a live backend we stream it so the attack
   * unfolds in the inspector; if streaming is unavailable we fall back to
   * the blocking call, and in demo mode to the local simulation.
   */
  const execute = async (scenarioId: number) => {
    setBusyId(scenarioId);
    const scenario = scenarios.find((s) => s.id === scenarioId);

    if (live) {
      setLiveRun({ ...EMPTY_LIVE, scenarioName: scenario?.name ?? '', message: 'Starting execution…' });
      const res = await streamScenarioRun(scenarioId, (msg) => {
        setLiveRun((prev) => applyStreamMsg(prev ?? EMPTY_LIVE, msg));
      });

      if (res.ok && res.runIds.length > 0) {
        await loadDetail(res.runIds[0]);
        await refresh();
        setLiveRun(null);
        setBusyId(null);
        return;
      }
      // Streaming unavailable — fall through to the blocking call.
      setLiveRun(null);
    }

    const res = await runScenario(scenarioId);
    if (res && typeof res.run_id === 'string') await loadDetail(res.run_id);
    await refresh();
    setBusyId(null);
  };

  const executeAll = async () => {
    setAllBusy(true);

    if (live) {
      setLiveRun({ ...EMPTY_LIVE, message: 'Starting batch…' });
      const res = await streamAllRuns((msg) => {
        setLiveRun((prev) => applyStreamMsg(prev ?? EMPTY_LIVE, msg));
      });
      if (res.ok && res.runIds.length > 0) {
        await loadDetail(res.runIds[res.runIds.length - 1]);
        await refresh();
        setLiveRun(null);
        setAllBusy(false);
        return;
      }
      setLiveRun(null);
    }

    await runAllScenarios();
    await refresh();
    setAllBusy(false);
  };

  const cancelLive = () => setLiveRun(null);

  const selectedRun = runs.find((r) => r.run_id === selectedRunId) ?? null;
  const isBusy = busyId !== null;
  const failedRuns = runs.filter((r) => (r.status || '').toLowerCase() === 'failed').length;

  const selectedViolation = useMemo(
    () => detail?.violations.find((v) => v.id === selectedViolationId) ?? null,
    [detail, selectedViolationId],
  );
  const evidenceIds = useMemo(
    () => new Set(selectedViolation?.evidence_event_ids ?? []),
    [selectedViolation],
  );

  // Group consecutive trace events by agent — a nested span view of the run.
  const traceGroups = useMemo(() => {
    const groups: { agent: string; events: TraceEvent[] }[] = [];
    for (const ev of detail?.trace ?? []) {
      const last = groups[groups.length - 1];
      if (last && last.agent === ev.agent) last.events.push(ev);
      else groups.push({ agent: ev.agent, events: [ev] });
    }
    return groups;
  }, [detail]);

  const exportReport = (format: 'json' | 'md') => {
    if (!detail) return;
    const base = `redops-report-${detail.run_id}`;
    if (format === 'json') {
      download(`${base}.json`, JSON.stringify({ generated_at: new Date().toISOString(), ...detail }, null, 2), 'application/json');
    } else {
      download(`${base}.md`, buildMarkdownReport(detail), 'text/markdown');
    }
  };

  return (
    <div className="min-h-screen bg-paper text-ink">
      {/* ── Top bar ── */}
      <header className="sticky top-0 z-30 bg-paper/85 backdrop-blur border-b border-line">
        <div className="max-w-7xl mx-auto px-6 h-14 flex items-center justify-between">
          <Logo />
          <div className="flex items-center gap-3">
            <span className="text-[11px] font-mono px-2 py-0.5 rounded border border-line bg-panel text-muted">
              v0.2.0-pipeline
            </span>
            <span
              className={`text-[11px] font-mono px-2 py-0.5 rounded border ${
                live === null
                  ? 'border-line bg-panel text-muted'
                  : live
                    ? 'border-emerald-200 bg-emerald-50 text-emerald-700'
                    : 'border-crimson/25 bg-crimson-faint text-crimson'
              }`}
            >
              {live === null ? 'connecting…' : live ? 'backend live' : 'demo mode'}
            </span>
            <button
              onClick={executeAll}
              disabled={allBusy || isBusy}
              className="btn-primary !py-1.5 !px-4 text-[13px] disabled:opacity-60"
            >
              <span>▶</span> {allBusy ? 'Running…' : 'Run All Scenarios'}
            </button>
          </div>
        </div>
      </header>

      <div className="max-w-7xl mx-auto px-6 py-8">
        {/* ── Demo-mode notice ── */}
        {live === false && (
          <div className="mb-6 flex items-start gap-3 rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 text-[13px] text-amber-800">
            <span aria-hidden="true" className="mt-0.5">⚠</span>
            <div className="flex-1">
              <b>Demo mode</b> — the API at <span className="font-mono">/api</span> is unreachable, so the
              console shows data captured from the real pipeline and simulates new runs locally. Start the
              backend (<span className="font-mono">uvicorn main:app --port 8000</span>) for live execution.
            </div>
            <button
              onClick={() => void refresh()}
              className="shrink-0 text-xs font-medium border border-amber-300 px-2.5 py-1 rounded-md hover:bg-amber-100 transition-colors"
            >
              Retry
            </button>
          </div>
        )}

        {/* ── Title ── */}
        <div className="mb-8">
          <div className="eyebrow mb-2">Defensive multi-agent security evaluation</div>
          <h1 className="font-display text-3xl sm:text-4xl">
            AGENT <span className="text-crimson">CONSOLE</span>
          </h1>
          <p className="text-muted text-sm mt-3 max-w-xl">
            Run scenarios against the simulated requester → vendor → approver → purchaser → auditor pipeline, inspect
            deception traces, and verify guards neutralize every attack path.
          </p>
        </div>

        {/* ── Metrics ── */}
        <div className="grid grid-cols-2 lg:grid-cols-4 gap-4 mb-10">
          <MetricCard label="Active Scenarios" value={scenarios.length} note="Deterministic multi-agent cases" />
          <MetricCard
            label="Total Violations"
            value={metrics?.total_violations ?? '—'}
            note={failedRuns > 0 ? `Detected across all runs · ${failedRuns} failed run${failedRuns > 1 ? 's' : ''}` : 'Detected across all runs'}
            tone="red"
          />
          <MetricCard
            label="Blocked by Defense"
            value={metrics?.blocked_by_defense ?? '—'}
            note="Guards verified at trust boundaries"
            tone="green"
          />
          <MetricCard
            label="Avg Latency"
            value={metrics ? `${metrics.avg_latency_ms.toFixed(1)} ms` : '—'}
            note="Local deterministic execution"
          />
        </div>

        {/* ── Main grid ── */}
        <div className="grid lg:grid-cols-5 gap-6">
          {/* Left column */}
          <div className="lg:col-span-3 space-y-6">
            {/* Scenarios */}
            <section className="panel panel-shadow overflow-hidden">
              <div className="px-5 py-3.5 border-b border-line flex items-center justify-between bg-lab/50">
                <h2 className="text-sm font-semibold">Security Scenarios</h2>
                <span className="font-mono text-[11px] text-muted">Requester → Vendor → Approver → Purchaser → Auditor</span>
              </div>
              <div className="divide-y divide-line">
                {loading && scenarios.length === 0 && (
                  <div className="px-5 py-8 text-center text-sm text-muted">Loading scenarios…</div>
                )}
                {scenarios.map((sc) => (
                  <div key={sc.id} className="px-5 py-4 hover:bg-crimson-faint/40 transition-colors">
                    <div className="flex items-start justify-between gap-4">
                      <div>
                        <div className="flex flex-wrap items-center gap-2">
                          <span className="font-mono text-[11px] px-2 py-0.5 rounded border border-line bg-lab text-muted">
                            SC-{String(sc.id).padStart(2, '0')}
                          </span>
                          <h3 className="font-medium text-sm">{sc.name}</h3>
                          {sc.expected_outcome === 'failed' && <Badge tone="amber">failure demo</Badge>}
                        </div>
                        <p className="text-muted text-[13px] mt-1">{sc.description}</p>
                        <div className="flex flex-wrap gap-1.5 mt-2.5">
                          {sc.expected_violations.length > 0 ? (
                            sc.expected_violations.map((v) => (
                              <Badge key={v} tone="red">
                                {v}
                              </Badge>
                            ))
                          ) : (
                            <Badge tone="green">Positive Baseline</Badge>
                          )}
                        </div>
                      </div>
                      <button
                        onClick={() => execute(sc.id)}
                        disabled={isBusy || allBusy}
                        className="btn-secondary !py-1.5 !px-3 text-xs whitespace-nowrap disabled:opacity-50"
                      >
                        {busyId === sc.id ? 'Running…' : 'Run Test'}
                      </button>
                    </div>
                  </div>
                ))}
              </div>
            </section>

            {/* Runs table */}
            <section className="panel panel-shadow overflow-hidden">
              <div className="px-5 py-3.5 border-b border-line bg-lab/50 flex items-center justify-between">
                <h2 className="text-sm font-semibold">Recent Execution Runs</h2>
                <span className="font-mono text-[11px] text-muted">click a row to inspect</span>
              </div>
              <div className="overflow-x-auto">
                <table className="w-full text-left text-sm">
                  <thead className="text-[11px] uppercase tracking-wider text-muted border-b border-line">
                    <tr>
                      <th className="px-5 py-2.5 font-mono">Run ID</th>
                      <th className="px-5 py-2.5">Scenario</th>
                      <th className="px-5 py-2.5">Status</th>
                      <th className="px-5 py-2.5">Violations</th>
                      <th className="px-5 py-2.5">Attack Paths</th>
                      <th className="px-5 py-2.5">Defense</th>
                      <th className="px-5 py-2.5">Latency</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-line">
                    {loading && runs.length === 0 && (
                      <tr>
                        <td colSpan={7} className="px-5 py-8 text-center text-muted">Loading runs…</td>
                      </tr>
                    )}
                    {runs.map((r) => (
                      <tr
                        key={r.run_id}
                        onClick={() => loadDetail(r.run_id)}
                        className={`cursor-pointer transition-colors ${
                          selectedRunId === r.run_id ? 'bg-crimson-faint/60' : 'hover:bg-lab/60'
                        }`}
                      >
                        <td className="px-5 py-3 font-mono text-xs text-crimson">{r.run_id}</td>
                        <td className="px-5 py-3 font-medium text-[13px]">{r.scenario_name}</td>
                        <td className="px-5 py-3"><StatusBadge status={r.status} /></td>
                        <td className="px-5 py-3 tabular-nums">
                          {r.violation_count > 0 ? <span className="text-crimson font-semibold">{r.violation_count}</span> : <span className="text-muted">0</span>}
                        </td>
                        <td className="px-5 py-3 tabular-nums">
                          {r.attack_path_count > 0 ? <span className="text-amber-600 font-semibold">{r.attack_path_count}</span> : <span className="text-muted">None</span>}
                        </td>
                        <td className="px-5 py-3">
                          <Badge tone={r.defense_verdict === 'all_blocked' ? 'green' : r.defense_verdict === 'some_bypassed' ? 'amber' : 'gray'}>
                            {r.defense_verdict ?? 'clean'}
                          </Badge>
                        </td>
                        <td className="px-5 py-3 text-muted tabular-nums text-[13px]">{r.latency_ms} ms</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </section>
          </div>

          {/* Right column: inspector */}
          <div className="lg:col-span-2">
            {liveRun ? (
              <LiveExecutionPanel state={liveRun} onCancel={cancelLive} />
            ) : (
            <section className="panel panel-shadow p-5 lg:sticky lg:top-20 lg:max-h-[calc(100vh-6rem)] lg:overflow-y-auto">
              <div className="flex items-center justify-between mb-4 gap-2">
                <h2 className="text-sm font-semibold">Attack Path &amp; Defense Trace</h2>
                <div className="flex items-center gap-2">
                  {detail && (
                    <>
                      <button
                        onClick={() => exportReport('md')}
                        className="text-[11px] font-mono border border-line px-2 py-1 rounded hover:bg-lab transition-colors"
                        title="Download Markdown report"
                      >
                        .md
                      </button>
                      <button
                        onClick={() => exportReport('json')}
                        className="text-[11px] font-mono border border-line px-2 py-1 rounded hover:bg-lab transition-colors"
                        title="Download JSON report"
                      >
                        .json
                      </button>
                    </>
                  )}
                  <span className="font-mono text-[11px] text-muted">{selectedRun?.run_id ?? 'select a run'}</span>
                </div>
              </div>

              {selectedRun || detail ? (
                <div className="space-y-5">
                  <div className="bg-lab border border-line rounded-lg p-3.5 text-xs">
                    <div className="text-muted font-semibold uppercase tracking-wide text-[10px]">Scenario</div>
                    <div className="font-medium mt-0.5 flex items-center gap-2">
                      {detail?.scenario_name ?? selectedRun?.scenario_name}
                      {(detail?.status ?? selectedRun?.status) && (
                        <StatusBadge status={detail?.status ?? selectedRun?.status ?? ''} />
                      )}
                    </div>
                    <div className="text-muted mt-2 flex gap-4">
                      <span>
                        Violations <b className="text-crimson">{detail?.violations.length ?? selectedRun?.violation_count ?? 0}</b>
                      </span>
                      <span>
                        Attack paths <b className="text-amber-600">{detail?.attack_paths.length ?? selectedRun?.attack_path_count ?? 0}</b>
                      </span>
                      {detail && (
                        <span>
                          Latency <b>{detail.latency_ms} ms</b>
                        </span>
                      )}
                    </div>
                  </div>

                  {/* Failure & recovery */}
                  {detail?.error && (
                    <div className="border border-crimson/25 bg-crimson-faint/60 rounded-lg p-3.5">
                      <div className="text-[10px] font-semibold uppercase tracking-wider text-crimson mb-1">
                        Execution Failed
                      </div>
                      <p className="font-mono text-[11px] text-ink break-words">{detail.error}</p>
                      {detail.defenses.some((d) => d.verdict === 'blocked') && (
                        <p className="text-[12px] text-muted mt-2">
                          <b className="text-emerald-700">Recovered:</b> the defended re-run rejected the malformed
                          payload at the trust boundary and completed cleanly.
                        </p>
                      )}
                    </div>
                  )}

                  {/* Findings */}
                  {detail && detail.violations.length > 0 && (
                    <div>
                      <div className="text-[10px] font-semibold text-muted uppercase tracking-wider mb-2.5">
                        Findings ({detail.violations.length})
                      </div>
                      <div className="space-y-2">
                        {detail.violations.map((v) => {
                          const active = v.id === selectedViolationId;
                          return (
                            <button
                              key={v.id}
                              onClick={() => setSelectedViolationId(active ? null : v.id)}
                              className={`w-full text-left border rounded-lg p-3 transition-colors ${
                                active ? 'border-crimson/40 bg-crimson-faint/60' : 'border-crimson/20 bg-crimson-faint/20 hover:bg-crimson-faint/40'
                              }`}
                            >
                              <div className="flex items-center gap-2">
                                <Badge tone={v.severity === 'critical' || v.severity === 'high' ? 'red' : 'amber'}>
                                  {v.severity}
                                </Badge>
                                <span className="font-mono text-[10px] text-muted">{v.category}</span>
                              </div>
                              <div className="text-sm font-medium mt-1">{v.title}</div>
                              {active && (
                                <>
                                  <p className="text-[12px] text-muted mt-1 leading-relaxed">{v.description}</p>
                                  {v.root_cause && (
                                    <p className="text-[12px] mt-2">
                                      <span className="font-semibold text-crimson">Root cause:</span>{' '}
                                      <span className="text-muted">{v.root_cause}</span>
                                    </p>
                                  )}
                                  <p className="text-[10px] font-mono text-muted mt-2">
                                    {v.evidence_event_ids.length} evidence event{v.evidence_event_ids.length === 1 ? '' : 's'} highlighted below
                                  </p>
                                </>
                              )}
                            </button>
                          );
                        })}
                      </div>
                    </div>
                  )}

                  {/* Trace explorer */}
                  {detail && (
                    <div>
                      <div className="text-[10px] font-semibold text-muted uppercase tracking-wider mb-2.5">
                        Execution Trace — {detail.trace.length} events
                      </div>
                      <div className="border border-line rounded-lg overflow-hidden bg-lab/40">
                        <div className="divide-y divide-line max-h-[360px] overflow-y-auto">
                          {traceGroups.map((group, gi) => (
                            <div key={`${group.agent}-${gi}`}>
                              <div className="px-3 py-1.5 bg-panel border-y border-line first:border-t-0 flex items-center gap-2">
                                <span className="font-mono text-[10px] font-semibold uppercase tracking-wider text-ink">
                                  {group.agent}
                                </span>
                                <span className="font-mono text-[9px] text-muted">
                                  {group.events.length} event{group.events.length === 1 ? '' : 's'}
                                </span>
                              </div>
                              {group.events.map((ev) => {
                                const isError = ev.kind === 'error';
                                const isGuard = Boolean(ev.metadata?.defense_triggered);
                                const untrusted = !ev.trusted && !isGuard;
                                const evidence = evidenceIds.has(ev.id);
                                const open = openEventId === ev.id;
                                return (
                                  <div key={ev.id}>
                                    <button
                                      onClick={() => setOpenEventId(open ? null : ev.id)}
                                      className={`w-full text-left flex gap-2.5 px-3 py-2 hover:bg-panel/80 transition-colors ${
                                        evidence ? 'ring-1 ring-inset ring-crimson/50' : ''
                                      }`}
                                    >
                                      <span
                                        className={`mt-1 w-[9px] h-[9px] shrink-0 rounded-full ${
                                          isError || untrusted ? 'bg-crimson' : isGuard ? 'bg-emerald-500' : 'bg-emerald-500/60'
                                        }`}
                                      />
                                      <div className="min-w-0 flex-1">
                                        <div className="flex flex-wrap items-center gap-1.5">
                                          <span
                                            className={`text-[11px] font-medium ${
                                              isError || untrusted ? 'text-crimson' : isGuard ? 'text-emerald-700' : 'text-ink'
                                            }`}
                                          >
                                            {ev.action}
                                          </span>
                                          {untrusted && <Badge tone="red">untrusted</Badge>}
                                          {isError && <Badge tone="red">error</Badge>}
                                          {isGuard && <Badge tone="green">guard</Badge>}
                                          {evidence && <Badge tone="amber">evidence</Badge>}
                                        </div>
                                        <div className="text-[10px] text-muted font-mono">{ev.kind}</div>
                                      </div>
                                      <span className="font-mono text-[9px] text-muted pt-0.5 shrink-0">
                                        {ev.timestamp.slice(11, 19)}
                                      </span>
                                    </button>
                                    {open && (
                                      <div className="px-3 pb-2.5 -mt-1">
                                        <div className="rounded-md border border-line bg-panel p-2.5 font-mono text-[10px] space-y-1.5">
                                          <div>
                                            <span className="text-muted">input:</span>{' '}
                                            <span className="break-all text-ink">{JSON.stringify(ev.input_data)}</span>
                                          </div>
                                          <div>
                                            <span className="text-muted">output:</span>{' '}
                                            <span className="break-all text-ink">{JSON.stringify(ev.output_data)}</span>
                                          </div>
                                          {Object.keys(ev.metadata ?? {}).length > 0 && (
                                            <div>
                                              <span className="text-muted">metadata:</span>{' '}
                                              <span className="break-all text-ink">{JSON.stringify(ev.metadata)}</span>
                                            </div>
                                          )}
                                          <div>
                                            <span className="text-muted">event id:</span>{' '}
                                            <span className="text-crimson">{ev.id}</span>
                                          </div>
                                        </div>
                                      </div>
                                    )}
                                  </div>
                                );
                              })}
                            </div>
                          ))}
                        </div>
                      </div>
                    </div>
                  )}

                  {/* Verified defenses — every defense with its code-level fix */}
                  {detail && detail.defenses.length > 0 && (
                    <div className="border-t border-line pt-4">
                      <div className="text-[10px] font-semibold text-emerald-700 uppercase tracking-wider mb-2">
                        Verified Defenses ({detail.defenses.length})
                      </div>
                      <div className="space-y-3">
                        {detail.defenses.map((d) => (
                          <div
                            key={d.defense.id}
                            className={`p-3 rounded-lg text-xs border ${
                              d.verdict === 'blocked'
                                ? 'bg-emerald-50 border-emerald-200'
                                : 'bg-amber-50 border-amber-200'
                            }`}
                          >
                            <div className="flex items-center justify-between gap-2">
                              <span className={`font-semibold ${d.verdict === 'blocked' ? 'text-emerald-800' : 'text-amber-800'}`}>
                                {d.defense.name}
                              </span>
                              <Badge tone={d.verdict === 'blocked' ? 'green' : 'amber'}>{d.verdict}</Badge>
                            </div>
                            <p className="text-muted mt-1.5 leading-relaxed">{d.explanation}</p>
                            <p className="font-mono text-[10px] text-muted mt-2">{d.defense.code_location}</p>
                            <details className="mt-2">
                              <summary className="cursor-pointer font-medium text-ink select-none">
                                Recommended fix ▸
                              </summary>
                              <p className="text-muted mt-1.5 leading-relaxed">{d.defense.description}</p>
                              <pre className="mt-1.5 p-2 bg-panel border border-line rounded text-[10px] font-mono overflow-x-auto whitespace-pre-wrap break-words text-ink">
                                {d.defense.fix_description}
                              </pre>
                            </details>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}

                  {/* No-detail loading */}
                  {!detail && selectedRunId && (
                    <div className="text-center py-8 text-sm text-muted">Loading trace…</div>
                  )}
                </div>
              ) : (
                <div className="text-center py-12 text-muted text-sm">
                  Select a scenario execution or run to inspect the detailed attack path and verify defense behavior.
                </div>
              )}
            </section>
            )}
          </div>
        </div>
      </div>

      {/* ── Footer ── */}
      <footer className="border-t border-line py-5">
        <div className="max-w-7xl mx-auto px-6 flex items-center justify-between text-xs text-muted">
          <span>© 2026 RedOps · Agent Console</span>
          <span className="font-mono">Simulated environment · no real purchases executed</span>
        </div>
      </footer>
    </div>
  );
}
